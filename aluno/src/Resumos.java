public class Resumos {
    private String tema;
    private String resumo;

    public void setTema(String tema){
        this.tema = tema;
    }

    public void setResumo(String resumo){
        this.resumo = resumo;
    }

    public String getTema() {
        return tema;
    }

    public String getResumo() {
        return resumo;
    }
}
